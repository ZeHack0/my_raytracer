#include "math/Transform.hpp"

Transform::Transform() {
    _identity();
}

void Transform::_identity() {
    for (int i = 0; i < 4; i++) {
        for (int j = 0; j < 4; j++) {
            _mat[i][j] = (i == j) ? 1.0 : 0.0;
        }
    }
}

Vector3d Transform::apply(const Vector3d& v) const {
    return v;
}

double Transform::getUniformScale() const {
    return 1.0;
}